/** The tip is read on access from the current-language dictionary: the language can change at runtime. */
function actionHelp(action: Action): ActionHelp {
  return {
    get tip() {
      return STR.tips[action];
    },
    topic: ACTION_TOPICS[action],
  };
}

export const ACTION_HELP = Object.fromEntries(ACTIONS.map((a) => [a, actionHelp(a)])) as Record<
  Action,
  ActionHelp
>;

/** Match a pathname against a route template (`:param` and `*` splat). */
export function matchRouteTemplate(template: string, pathname: string): boolean {
  if (template === "*") return true;
  if (template === pathname) return true;
  const tplParts = template.split("/").filter(Boolean);
  const pathParts = pathname.split("/").filter(Boolean);
  if (tplParts.length === 0) return pathParts.length === 0;

  let ti = 0;
  let pi = 0;
  while (ti < tplParts.length && pi < pathParts.length) {
    const t = tplParts[ti]!;
    if (t === "*") return true;
    if (t.startsWith(":")) {
      ti++;
      pi++;
      continue;
    }
    if (t !== pathParts[pi]) return false;
    ti++;
    pi++;
  }
  if (ti < tplParts.length && tplParts[ti] === "*") return true;
  return ti === tplParts.length && pi === pathParts.length;
}

/** Resolve the page help topic id for a location pathname. */
export function resolvePageTopic(pathname: string): string {
  const entries = Object.entries(PAGE_HELP);
  // Prefer specific routes over splat / help/*
  const ranked = entries.sort((a, b) => {
    const score = (t: string) => {
      if (t === "*") return 0;
      if (t.endsWith("/*")) return 1;
      if (t.includes(":")) return 2;
      return 3 + t.length;
    };
    return score(b[0]) - score(a[0]);
  });
  for (const [template, topicId] of ranked) {
    if (matchRouteTemplate(template, pathname)) return topicId;
  }
  return "pages/not-found";
}
